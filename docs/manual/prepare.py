#!/usr/bin/env python3
"""Embed repository fixtures without inventing a second CPU implementation.

Run from any directory. --check fails if the checked-in browser data is stale.
Only Python's standard library is needed; neither sbt nor a network is used.
"""

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
DEST = HERE / "assets" / "data.js"
REPLAY_CASES = ("isa_example", "consecutive_mul")
HAZARD_CASES = (
    "raw_mul_next_cycle", "mul_then_add_port", "early_halt_ld", "mac_store_read_ports"
)


def read_json(path):
    return json.loads((ROOT / path).read_text(encoding="utf-8"))


def make_data():
    data = {
        "machines": {
            "mvp-0": read_json("config/machine.json"),
            "mvp-1": read_json("config/machine-mvp1.json"),
        },
        "replays": {},
        "hazards": {},
        "goldenHex": (ROOT / "tests/golden/isa_example.hex").read_text().split(),
    }
    for name in REPLAY_CASES:
        case = read_json(f"tests/cases/{name}.json")
        trace_path = case["expect"]["trace"]
        trace = [json.loads(line) for line in (ROOT / trace_path).read_text().splitlines() if line]
        data["replays"][name] = {"case": case, "trace": trace, "source": trace_path}
    for name in HAZARD_CASES:
        data["hazards"][name] = read_json(f"tests/cases/{name}.json")
    # Prevent a future fixture containing HTML from terminating the embedded script.
    encoded = json.dumps(data, ensure_ascii=False, indent=2).replace("<", "\\u003c")
    return "// Generated by docs/manual/prepare.py; do not edit.\nwindow.VLIW_DATA = " + encoded + ";\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = make_data()
    if args.check:
        if not DEST.exists() or DEST.read_text(encoding="utf-8") != expected:
            raise SystemExit("manual data is stale: run python3 docs/manual/prepare.py")
        print("manual data matches machine descriptions and golden fixtures")
    else:
        DEST.parent.mkdir(parents=True, exist_ok=True)
        DEST.write_text(expected, encoding="utf-8")
        print("prepared manual data from machine descriptions and golden fixtures")


if __name__ == "__main__":
    main()
